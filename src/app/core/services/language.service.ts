import { Injectable, signal, effect } from '@angular/core';

export type Lang = 'en' | 'ar';

@Injectable({
  providedIn: 'root'
})
export class LanguageService {
  public currentLang = signal<Lang>((localStorage.getItem('preferredLang') as Lang) || 'en');

  constructor() {
    effect(() => {
      const lang = this.currentLang();
      localStorage.setItem('preferredLang', lang);
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
      document.documentElement.lang = lang;

      if (lang === 'ar') {
        document.body.classList.add('rtl-mode');
        document.body.classList.remove('ltr-mode');
      } else {
        document.body.classList.add('ltr-mode');
        document.body.classList.remove('rtl-mode');
      }
    });
  }

  public setLanguage(lang: Lang): void {
    this.currentLang.set(lang);
  }

  public toggleLanguage(): void {
    this.currentLang.update(v => v === 'en' ? 'ar' : 'en');
  }

  public get isArabic(): boolean {
    return this.currentLang() === 'ar';
  }

  public translate<T>(enValue: T, arValue: T): T {
    return this.currentLang() === 'ar' ? arValue : enValue;
  }

  public instant(key: string): string {
    if (!key) return '';
    const cleanKey = key.trim();
    const trans = translations[this.currentLang()];
    return trans[cleanKey] !== undefined ? trans[cleanKey] : key;
  }
}

